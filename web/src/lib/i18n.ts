export type Lang = 'de' | 'en';
const dicts: Record<Lang, Partial<Record<MessageKey, string>>> = { de, en };

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem('ph_lang');
    if (stored === 'de' || stored === 'en') return stored;
  } catch {
    /* ignore */
  }
  return 'de';
}

let current: Lang = initialLang();
document.documentElement.lang = current;

export function lang(): Lang {
  return current;
}
export function locale(): string {
  return current === 'de' ? 'de-DE' : 'en-US';
}
export function setLang(l: Lang) {
  try {
    localStorage.setItem('ph_lang', l);
  } catch {
    /* ignore */
  }
  current = l;
  location.reload();
}

/** Translate `key`, replacing `{name}` placeholders with `params`. */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  let s = dicts[current][key] ?? en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
